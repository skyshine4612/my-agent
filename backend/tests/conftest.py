class FakeEmbedder:
    """按关键词给方向的假向量：命中第 i 个词就在第 i 维置 1，其余为 0。

    余弦相似度因此完全由关键词重合度决定（重合 → 1，不重合 → 0），排序可精确断言。
    真实语义质量由端到端验证覆盖，单测只需要确定性、且不能依赖外部 embedding 服务。
    """

    KEYWORDS = ["西湖", "火锅", "长城", "经济型", "自然风光", "历史古迹"]

    def __init__(self, dim: int = 1024):
        self.dim = dim

    async def embed(self, texts):
        return [self._vec(t) for t in texts]

    def _vec(self, text):
        v = [0.0] * self.dim
        for i, kw in enumerate(self.KEYWORDS):
            if kw in text:
                v[i] = 1.0
        # 兜底方向：不含任何关键词的文本若给全零向量，pgvector 算余弦距离会得到 NaN
        if not any(v):
            v[self.dim - 1] = 1.0
        return v


