    """session 级建测试库结构：用独立 event loop 同步执行，
    避开 session 级 async fixture 与测试自身 loop 的绑定冲突。"""
    dsn = settings.supabase_test_database_url
    if dsn:
        asyncio.run(_apply_schema(dsn))


