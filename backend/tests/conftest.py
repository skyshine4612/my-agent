# ---------------------------------------------------------------------------
# auth 桩：角色 + auth.users + auth.uid()
#
# 角色：Supabase 镜像预置了 anon / authenticated / service_role，非 Supabase 的库要自建。
# 后端每条业务查询都在事务里 set_config('role','authenticated')，缺这个角色会直接报错。
# ---------------------------------------------------------------------------
AUTH_STUB_SQL = """
do $$ begin
    if not exists (select 1 from pg_roles where rolname = 'authenticated') then
        create role authenticated nologin;
    end if;
end $$;

-- search_path 必须含 extensions：vector 类型装在那儿，代码里 `$4::vector` 这类不带 schema
-- 的 cast 得靠 search_path 找到它。主库的这项由 Supabase 镜像预置，测试库自建角色要补上，
-- 否则「主库能跑、测试库报 type vector does not exist」。
alter role authenticated set search_path = "$user", public, extensions;

create schema if not exists auth;

-- 只有 id 一列：满足外键，测试造用户一行 insert 即可
create table if not exists auth.users(
    id uuid primary key
);

-- 与 Supabase 真实实现同构：从 request.jwt.claims 的 sub 读当前用户
create or replace function auth.uid() returns uuid
language sql stable as $$
    select coalesce(
        nullif(current_setting('request.jwt.claim.sub', true), ''),
        (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
    )::uuid
$$;
"""

# ---------------------------------------------------------------------------
# 业务表 + RLS：与生产库一致
#
# 放进 Supabase 这套栈的表必须全开 RLS，否则会被 PostgREST 用公开的 anon key 直接读写。
# 后端之所以能受策略约束，是因为每条业务查询都跑在 rls_conn 的事务里（切角色 + 注入 claims）。
# ---------------------------------------------------------------------------
BUSINESS_SQL = """
-- vector 扩展：documents.embedding / long_term_memory.embedding 依赖它。
-- 主库的 extensions schema 由 Supabase 镜像预置，测试库是手工建的，这里补上。
create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists conversations(
    id          text primary key,
    user_id     uuid not null references auth.users(id) on delete cascade,
    title       text,
    created_at  timestamptz default now()
);
create index if not exists conversations_user_idx on conversations(user_id, created_at desc);

-- conv_id 级联：删会话时消息自动跟着删
create table if not exists messages(
    id          bigint generated by default as identity primary key,
    conv_id     text not null references conversations(id) on delete cascade,
    role        text,
    content     text,
    created_at  timestamptz default now()
);
create index if not exists messages_conv_idx on messages(conv_id, id);

create table if not exists short_term_memory(
    id              bigint generated by default as identity primary key,
    conversation_id text not null references conversations(id) on delete cascade,
    role            text,
    content         text,
    created_at      timestamptz default now()
);
create index if not exists stm_conv_idx on short_term_memory(conversation_id, id);

-- 按开发阶段约定：改表结构直接重建，不写 ALTER 迁移。
-- 用 drop 而非 if not exists：让测试库结构永远与这里的 DDL 一致（本表没有外部依赖，可安全重建）。
drop table if exists long_term_memory;
create table long_term_memory(
    id          bigint generated by default as identity primary key,
    user_id     uuid not null references auth.users(id) on delete cascade,
    fact        text not null,
    importance  double precision default 0.5,
    embedding   vector(1024),
    created_at  timestamptz default now()
);
create index if not exists ltm_user_idx on long_term_memory(user_id, importance desc);
create index if not exists ltm_embedding_idx
    on long_term_memory using hnsw (embedding vector_cosine_ops);

-- 知识库：全局共享，不做 per-user 隔离，任何登录用户可读可写。
-- 与 long_term_memory 分开建表而非共用一张 + source_type：两者隔离策略根本不同
-- （这里是 using(true)，那边是 user_id = auth.uid()），共用会让策略退化成按类型分支。
--
-- images 是 chunk 级的图片清单 [{"key": ..., "desc": ...}]：
-- key 是 knowledge 桶里的对象 key（上传失败写 null，前端按占位符渲染）；
-- **新行一律写数组，NULL 专属旧行** —— 区分「历史上没这列」与「这篇没图」。
--
-- 用 drop 而非 if not exists：让测试库结构永远与这里的 DDL 一致，加列才生效
-- （documents 与 long_term_memory 一样没有外部依赖，可安全重建）。
drop table if exists documents;
create table documents(
    id          bigint generated by default as identity primary key,
    title       text,
    content     text,
    chunk_index int,
    embedding   vector(1024) not null,
    source_url  text,
    images      jsonb,
    created_at  timestamptz default now()
);
create index if not exists documents_embedding_idx
    on documents using hnsw (embedding vector_cosine_ops);

-- 会话文件：字节在 Storage 的 files 桶，这里只存元数据。
create table if not exists files(
    id              text primary key,
    user_id         uuid not null references auth.users(id) on delete cascade,
    conversation_id text not null references conversations(id) on delete cascade,
    name            text not null,
    size            bigint not null,
    source          text not null default 'upload',
    storage_path    text not null,
    created_at      timestamptz default now()
);
create index if not exists files_conv_idx on files(conversation_id, created_at desc);

alter table conversations      enable row level security;
alter table messages           enable row level security;
alter table short_term_memory  enable row level security;
alter table long_term_memory   enable row level security;
alter table documents          enable row level security;
alter table files              enable row level security;

drop policy if exists conv_own on conversations;
create policy conv_own on conversations
    for all to authenticated
    using      (user_id = auth.uid())
    with check (user_id = auth.uid());

drop policy if exists ltm_own on long_term_memory;
create policy ltm_own on long_term_memory
    for all to authenticated
    using      (user_id = auth.uid())
    with check (user_id = auth.uid());

-- 消息表里只有 conv_id，经会话归属判定；子查询里的 conversations 会再应用它自己的策略，
-- 范围自动收窄到本人的会话。列名限定成 messages.conv_id，避免与外层同名时歧义。
drop policy if exists msg_own on messages;
create policy msg_own on messages
    for all to authenticated
    using      (exists (select 1 from conversations c
                        where c.id = messages.conv_id and c.user_id = auth.uid()))
    with check (exists (select 1 from conversations c
                        where c.id = messages.conv_id and c.user_id = auth.uid()));

drop policy if exists stm_own on short_term_memory;
create policy stm_own on short_term_memory
    for all to authenticated
    using      (exists (select 1 from conversations c
                        where c.id = short_term_memory.conversation_id
                          and c.user_id = auth.uid()))
    with check (exists (select 1 from conversations c
                        where c.id = short_term_memory.conversation_id
                          and c.user_id = auth.uid()));

drop policy if exists doc_read on documents;
create policy doc_read on documents
    for select to authenticated using (true);

drop policy if exists doc_write on documents;
create policy doc_write on documents
    for insert to authenticated with check (true);

-- 删除同样放开：知识库定位就是共享语料，读都 using(true) 了，删再按人拦住没意义。
-- 不授 update：文档不可改，要改就删了重传（重新上传即新增一批块）。
drop policy if exists doc_delete on documents;
create policy doc_delete on documents
    for delete to authenticated using (true);

-- 会话文件按用户隔离，与 conv_own 同构（这里自带 user_id，不必经 conversations 绕）
drop policy if exists files_own on files;
create policy files_own on files
    for all to authenticated
    using      (user_id = auth.uid())
    with check (user_id = auth.uid());

grant usage on schema public to authenticated;
-- 无此授权时 PostgreSQL 会在 search_path 里静默跳过 extensions，
-- 报错是「type vector does not exist」而非权限不足，容易误判成扩展没装。
grant usage on schema extensions to authenticated;
grant select, insert, update, delete on
    conversations, messages, short_term_memory, long_term_memory
    to authenticated;
grant select, insert, delete on documents to authenticated;
grant select, insert, delete on files to authenticated;
grant usage, select on sequence
    messages_id_seq, short_term_memory_id_seq, long_term_memory_id_seq, documents_id_seq
    to authenticated;

-- 检索函数：按余弦距离取 top-k。stable + 默认 security invoker，所以 RLS 照常生效，
-- 不能改成 security definer，否则会绕过策略。
-- 显式 set search_path：函数体用到 public.documents 与 extensions 的 <=> 运算符，固定下来防 search_path 注入。
create or replace function match_documents(
    query_embedding vector(1024), match_count int default 3
) returns table(id bigint, title text, content text, source_url text, similarity float)
language sql stable
set search_path = public, extensions
as $$
    select d.id, d.title, d.content, d.source_url,
           1 - (d.embedding <=> query_embedding) as similarity
    from documents d
    order by d.embedding <=> query_embedding
    limit match_count;
$$;

-- 长期记忆检索：与 match_documents 的差别是多一道 user_id 过滤（长期记忆按用户隔离）。
-- 显式过滤 + 函数默认 security invoker 下的 RLS，是双保险；embedding 为空的历史条目直接排除。
create or replace function match_long_term(
    query_embedding vector(1024), match_user_id uuid, match_count int default 20
) returns table(id bigint, fact text, importance double precision, similarity float)
language sql stable
set search_path = public, extensions
as $$
    select m.id, m.fact, m.importance,
           1 - (m.embedding <=> query_embedding) as similarity
    from long_term_memory m
    where m.user_id = match_user_id and m.embedding is not null
    order by m.embedding <=> query_embedding
    limit match_count;
$$;
"""


async def _apply_schema(dsn: str) -> None:
    """把 auth 桩与业务 schema 套到测试库（幂等）。"""
    conn = await asyncpg.connect(dsn)
    try:
        # 无参数调用走 simple query protocol，支持一次执行多条语句
        await conn.execute(AUTH_STUB_SQL)
        await conn.execute(BUSINESS_SQL)
    finally:
        await conn.close()


